"""Check the marker QComponent geometry against the fixed e-beam marker references.

Compares the polygons generated by `pattern design/marker/nthu_tiau_marker.py` and
`pattern design/marker/tsri_a12_mark.py` with
`Fabrication output/Template/{NTHU,TSRI} ebeam gds/*.gds` (union area and XOR on the
reference layer), and builds each QComponent once in a qiskit-metal design.

Optional `--write-dir DIR` writes the generated marker GDS files (inspection only; never put
them in a delivery or in Template/).

Usage (repository root, qmetal):
    python -I -X utf8 -B code/general/check_marker_references.py [--write-dir tmp/markers]
"""

import argparse
import json
import sys
from pathlib import Path

import gdstk

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'code' / 'general'))
from project_paths import configure  # noqa: E402

configure(__file__)

import nthu_tiau_marker as nthu  # noqa: E402
import tsri_a12_mark as tsri  # noqa: E402

TEMPLATE = ROOT / 'Fabrication output' / 'Template'
# Match = no XOR region survives a 5 nm erosion (i.e. every difference is < 10 nm wide). The
# wafer reference carries 1-2 nm coordinate noise; polygon counts are informational because the
# TSRI reference draws crosses / L marks as overlapping rectangles.
SLIVER_UM = 0.005


def to_gdstk(geom, layer, datatype):
    """shapely (Multi)Polygon with holes -> list of gdstk polygons."""
    parts = getattr(geom, 'geoms', [geom])
    out = []
    for g in parts:
        outer = [gdstk.Polygon(list(g.exterior.coords)[:-1], layer=layer, datatype=datatype)]
        holes = [gdstk.Polygon(list(h.coords)[:-1]) for h in g.interiors]
        out += gdstk.boolean(outer, holes, 'not', layer=layer, datatype=datatype) if holes else outer
    return out


def compare(name, ref_file, polys, layer):
    lib = gdstk.read_gds(str(ref_file))
    ref = [p for c in lib.top_level() for p in c.get_polygons() if (p.layer, p.datatype) == layer]
    gen = [q for g in polys for q in to_gdstk(g, *layer)]
    xor = gdstk.boolean(ref, gen, 'xor')
    wide = gdstk.offset(xor, -SLIVER_UM) if xor else []
    res = dict(reference=str(ref_file.relative_to(ROOT).as_posix()), layer=list(layer),
               n_reference_polygons=len(ref), n_generated_polygons=len(polys),
               union_area_reference_um2=round(sum(p.area() for p in gdstk.boolean(ref, [], 'or')), 4),
               union_area_generated_um2=round(sum(p.area() for p in gdstk.boolean(gen, [], 'or')), 4),
               xor_area_um2=round(sum(p.area() for p in xor), 6),
               xor_wider_than_10nm=len(wide))
    res['match'] = res['xor_wider_than_10nm'] == 0
    return name, res, gen


def build_components():
    """Instantiate every marker QComponent once; return {name: number of qgeometry rows}."""
    from qiskit_metal import designs
    design = designs.DesignPlanar({}, overwrite_enabled=True)
    design.chips.main.size.size_x = '100mm'
    design.chips.main.size.size_y = '100mm'
    comps = [nthu.TiAuChipMarker(design, 'tiau_chip'),
             nthu.TiAuWaferMarker(design, 'tiau_wafer'),
             tsri.TSRIA12Mark(design, 'a12', options=dict(ground_opening='True'))]
    return {c.name: int(len(design.qgeometry.tables['poly'].query(f'component == {c.id}')))
            for c in comps}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--write-dir', type=Path, help='write generated marker GDS files here')
    args = ap.parse_args()

    chip = [g for gs in nthu.chip_marker_sites().values() for g in gs]
    wafer = [g for gs in nthu.wafer_marker_sites().values() for g in gs]
    checks = [
        compare('nthu_tiau_chip', TEMPLATE / 'NTHU ebeam gds' / 'TiAu_marker_chip_single_die.gds',
                chip, nthu.CHIP_LAYER),
        compare('nthu_tiau_wafer', TEMPLATE / 'NTHU ebeam gds' / 'TiAu_marker_wafer_4inch.gds',
                wafer, nthu.WAFER_LAYER),
        compare('tsri_a12', TEMPLATE / 'TSRI ebeam gds' / 'A12mark_TSRI.gds',
                tsri.a12_polygons(include_corners=True), tsri.REFERENCE_LAYER),
    ]
    report = {name: res for name, res, _ in checks}
    report['qcomponent_rows'] = build_components()

    if args.write_dir:
        args.write_dir.mkdir(parents=True, exist_ok=True)
        for name, _, gen in checks:
            lib = gdstk.Library(unit=1e-6, precision=1e-9)
            lib.new_cell(name.upper()).add(*gen)
            lib.write_gds(str(args.write_dir / f'{name}_generated.gds'))

    print(json.dumps(report, indent=2))
    ok = all(r['match'] for n, r in report.items() if n != 'qcomponent_rows')
    print('ALL MATCH' if ok else 'MISMATCH')
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
